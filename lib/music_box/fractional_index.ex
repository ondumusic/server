defmodule MusicBox.FractionalIndex do
  @moduledoc """
  This module is generated by Claude Opus.

  It is a port of the `fractional-indexing` NPM package so we can provide server
  side validation and rebalancing functionality for our playlist items. The
  reason for a port is that I could not find a reliable existing library, there
  is one for Gleam but I did not feel like adding the Gleam toolchain for what
  is essentially a small library. So instead I had Claude generate a port and
  tests matching the original package.
  """

  @base62_digits "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
  @default_max_length 100

  def max_length, do: @default_max_length

  defmodule Error do
    defexception [:message]
  end

  @doc """
  Returns a key strictly between `a` and `b`. Pass `nil` for an unbounded side.

  Raises `FractionalIndex.Error` if either input is malformed or `a >= b`.
  """
  @spec generate_key_between(String.t() | nil, String.t() | nil, String.t()) :: String.t()
  def generate_key_between(a, b, digits \\ @base62_digits)

  def generate_key_between(a, b, digits) do
    if a != nil, do: validate_order_key(a, digits)
    if b != nil, do: validate_order_key(b, digits)

    if a != nil and b != nil and a >= b do
      raise Error, message: "#{a} >= #{b}"
    end

    do_generate_key_between(a, b, digits)
  end

  defp do_generate_key_between(nil, nil, digits) do
    "a" <> String.first(digits)
  end

  defp do_generate_key_between(nil, b, digits) when is_binary(b) do
    zero = String.first(digits)
    smallest_int = "A" <> String.duplicate(zero, 26)
    ib = get_integer_part(b)
    fb = binary_part(b, byte_size(ib), byte_size(b) - byte_size(ib))

    cond do
      ib == smallest_int ->
        ib <> midpoint("", fb, digits)

      ib < b ->
        ib

      true ->
        case decrement_integer(ib, digits) do
          nil -> raise Error, message: "cannot decrement any more"
          res -> res
        end
    end
  end

  defp do_generate_key_between(a, nil, digits) when is_binary(a) do
    ia = get_integer_part(a)
    fa = binary_part(a, byte_size(ia), byte_size(a) - byte_size(ia))

    case increment_integer(ia, digits) do
      nil -> ia <> midpoint(fa, nil, digits)
      i -> i
    end
  end

  defp do_generate_key_between(a, b, digits) when is_binary(a) and is_binary(b) do
    ia = get_integer_part(a)
    fa = binary_part(a, byte_size(ia), byte_size(a) - byte_size(ia))
    ib = get_integer_part(b)
    fb = binary_part(b, byte_size(ib), byte_size(b) - byte_size(ib))

    if ia == ib do
      ia <> midpoint(fa, fb, digits)
    else
      case increment_integer(ia, digits) do
        nil -> raise Error, message: "cannot increment any more"
        i when i < b -> i
        _ -> ia <> midpoint(fa, nil, digits)
      end
    end
  end

  @doc """
  Returns `n` distinct keys strictly between `a` and `b`, in sorted order.

  Used for batch inserts and for rebalancing (call with `nil, nil, length(items)`).
  """
  @spec generate_n_keys_between(String.t() | nil, String.t() | nil, non_neg_integer(), String.t()) ::
          [String.t()]
  def generate_n_keys_between(a, b, n, digits \\ @base62_digits)

  def generate_n_keys_between(_a, _b, 0, _digits), do: []
  def generate_n_keys_between(a, b, 1, digits), do: [generate_key_between(a, b, digits)]

  def generate_n_keys_between(a, nil, n, digits) when n > 1 do
    c = generate_key_between(a, nil, digits)
    walk_forward(c, n - 1, digits, [c])
  end

  def generate_n_keys_between(nil, b, n, digits) when n > 1 do
    c = generate_key_between(nil, b, digits)
    # walk_backward prepends each new (smaller) key, producing an ascending list.
    walk_backward(c, n - 1, digits, [c])
  end

  def generate_n_keys_between(a, b, n, digits) when is_binary(a) and is_binary(b) and n > 1 do
    mid = div(n, 2)
    c = generate_key_between(a, b, digits)

    generate_n_keys_between(a, c, mid, digits) ++
      [c] ++ generate_n_keys_between(c, b, n - mid - 1, digits)
  end

  defp walk_forward(_last, 0, _digits, acc), do: Enum.reverse(acc)

  defp walk_forward(last, remaining, digits, acc) do
    nxt = generate_key_between(last, nil, digits)
    walk_forward(nxt, remaining - 1, digits, [nxt | acc])
  end

  defp walk_backward(_first, 0, _digits, acc), do: acc

  defp walk_backward(first, remaining, digits, acc) do
    prv = generate_key_between(nil, first, digits)
    walk_backward(prv, remaining - 1, digits, [prv | acc])
  end

  @doc """
  Validates a key. Returns `:ok` or `{:error, reason}`.

  Use this on every write path before persisting.
  """
  @spec validate(String.t(), keyword()) :: :ok | {:error, String.t()}
  def validate(key, opts \\ [])

  def validate(key, opts) when is_binary(key) do
    digits = Keyword.get(opts, :digits, @base62_digits)
    max_length = Keyword.get(opts, :max_length, @default_max_length)

    cond do
      byte_size(key) == 0 ->
        {:error, "empty order key"}

      byte_size(key) > max_length ->
        {:error, "order key exceeds max length of #{max_length}"}

      not all_chars_in_digits?(key, digits) ->
        {:error, "order key contains characters outside the digit alphabet"}

      true ->
        try do
          validate_order_key(key, digits)
          :ok
        rescue
          e in Error -> {:error, e.message}
        end
    end
  end

  def validate(_, _), do: {:error, "order key must be a string"}

  # The head of a valid key is always a letter (a-z or A-Z), which is in the
  # base-62 alphabet; for custom alphabets this still holds because get_integer_length
  # would reject anything else. So checking every byte against the alphabet is correct.
  defp all_chars_in_digits?(key, digits) do
    key
    |> :binary.bin_to_list()
    |> Enum.all?(fn byte -> :binary.match(digits, <<byte>>) != :nomatch end)
  end

  defp validate_order_key("", _digits) do
    raise Error, message: "invalid order key: "
  end

  defp validate_order_key(key, digits) when is_binary(key) do
    zero = String.first(digits)
    smallest = "A" <> String.duplicate(zero, 26)

    if key == smallest do
      raise Error, message: "invalid order key: #{key}"
    end

    i = get_integer_part(key)
    f = binary_part(key, byte_size(i), byte_size(key) - byte_size(i))

    if f != "" and String.last(f) == zero do
      raise Error, message: "invalid order key: #{key}"
    end

    :ok
  end

  defp get_integer_part(""), do: raise(Error, message: "invalid order key: ")

  defp get_integer_part(key) do
    head = String.first(key)
    n = get_integer_length(head)

    if n > byte_size(key) do
      raise Error, message: "invalid order key: #{key}"
    end

    binary_part(key, 0, n)
  end

  defp get_integer_length(<<c>>) when c >= ?a and c <= ?z, do: c - ?a + 2
  defp get_integer_length(<<c>>) when c >= ?A and c <= ?Z, do: ?Z - c + 2
  defp get_integer_length(head), do: raise(Error, message: "invalid order key head: #{head}")

  defp validate_integer(""), do: raise(Error, message: "invalid integer part of order key: ")

  defp validate_integer(i) do
    if byte_size(i) != get_integer_length(String.first(i)) do
      raise Error, message: "invalid integer part of order key: #{i}"
    end
  end

  # Both inputs are *fractional parts*. `a` may be empty. `b` is nil or a
  # non-empty string with `a < b`. No trailing zeros allowed.
  defp midpoint(a, b, digits) do
    zero = String.first(digits)

    cond do
      b != nil and a >= b ->
        raise Error, message: "#{a} >= #{b}"

      (a != "" and String.last(a) == zero) or (b != nil and String.last(b) == zero) ->
        raise Error, message: "trailing zero"

      true ->
        midpoint_no_trailing_zero(a, b, digits, zero)
    end
  end

  defp midpoint_no_trailing_zero(a, b, digits, zero) do
    n = if b != nil, do: common_prefix_len(a, b, zero), else: 0

    if n > 0 do
      midpoint_with_common_prefix(a, b, digits, n)
    else
      midpoint_at_first_diff(a, b, digits)
    end
  end

  defp midpoint_with_common_prefix(a, b, digits, n) do
    a_rest = drop_prefix(a, n)
    b_rest = drop_prefix(b, n)
    binary_part(b, 0, n) <> midpoint(a_rest, b_rest, digits)
  end

  defp midpoint_at_first_diff(a, b, digits) do
    digit_a = if a == "", do: 0, else: digit_index(digits, String.first(a))
    digit_b = if b == nil, do: String.length(digits), else: digit_index(digits, String.first(b))

    cond do
      digit_b - digit_a > 1 ->
        mid = round_half_up_half_sum(digit_a, digit_b)
        String.at(digits, mid)

      b != nil and byte_size(b) > 1 ->
        String.first(b)

      true ->
        # b is nil or length-1. Keep a's first digit, recurse with no upper bound.
        String.at(digits, digit_a) <> midpoint(drop_prefix(a, 1), nil, digits)
    end
  end

  defp drop_prefix(nil, _n), do: ""
  defp drop_prefix(s, n) when byte_size(s) > n, do: binary_part(s, n, byte_size(s) - n)
  defp drop_prefix(_s, _n), do: ""

  defp common_prefix_len(a, b, zero) do
    common_prefix_len(a, b, zero, 0, byte_size(a), byte_size(b))
  end

  defp common_prefix_len(_a, _b, _zero, n, _la, lb) when n >= lb, do: n

  defp common_prefix_len(a, b, zero, n, la, lb) do
    ac = if n < la, do: binary_part(a, n, 1), else: zero
    bc = binary_part(b, n, 1)
    if ac == bc, do: common_prefix_len(a, b, zero, n + 1, la, lb), else: n
  end

  # round_half_up(0.5 * (a + b)) without floats
  defp round_half_up_half_sum(a, b) do
    s = a + b
    if rem(s, 2) == 0, do: div(s, 2), else: div(s + 1, 2)
  end

  defp digit_index(digits, ch) do
    case :binary.match(digits, ch) do
      :nomatch -> raise Error, message: "invalid digit: #{ch}"
      {pos, _} -> pos
    end
  end

  defp increment_integer(x, digits) do
    validate_integer(x)
    zero = String.first(digits)
    head = binary_part(x, 0, 1)
    digs = x |> binary_part(1, byte_size(x) - 1) |> String.graphemes()

    case bump_with_carry(digs, digits, zero, :forward) do
      {:ok, new_digs} -> head <> Enum.join(new_digs)
      {:overflow, wrapped_digs} -> promote_head_forward(head, wrapped_digs, zero)
    end
  end

  defp promote_head_forward("Z", _digs, zero), do: "a" <> zero
  defp promote_head_forward("z", _digs, _zero), do: nil

  defp promote_head_forward(head, digs, zero) do
    <<c::utf8>> = head
    new_head = <<c + 1::utf8>>

    if new_head > "a" do
      # crossed into longer-length lowercase territory: append a zero
      new_head <> Enum.join(digs) <> zero
    else
      # crossing within uppercase toward 'a': drop the last digit
      new_head <> Enum.join(Enum.drop(digs, -1))
    end
  end

  defp decrement_integer(x, digits) do
    validate_integer(x)
    last = String.last(digits)
    head = binary_part(x, 0, 1)
    digs = x |> binary_part(1, byte_size(x) - 1) |> String.graphemes()

    case bump_with_carry(digs, digits, last, :backward) do
      {:ok, new_digs} -> head <> Enum.join(new_digs)
      {:overflow, wrapped_digs} -> promote_head_backward(head, wrapped_digs, last)
    end
  end

  defp promote_head_backward("a", _digs, last), do: "Z" <> last
  defp promote_head_backward("A", _digs, _last), do: nil

  defp promote_head_backward(head, digs, last) do
    <<c::utf8>> = head
    new_head = <<c - 1::utf8>>

    if new_head < "Z" do
      new_head <> Enum.join(digs) <> last
    else
      new_head <> Enum.join(Enum.drop(digs, -1))
    end
  end

  # Walks digits right-to-left applying +1 (forward) or -1 (backward). Returns
  # `{:ok, new_digits}` if the change is contained in the digit positions, or
  # `{:overflow, wrapped_digits}` if it carries/borrows past position 0. In the
  # overflow case, every digit has been replaced by `fill` (zero for forward,
  # last digit for backward).
  defp bump_with_carry(digs, digits, fill, direction) do
    bump_with_carry(Enum.reverse(digs), digits, fill, direction, [])
  end

  defp bump_with_carry([], _digits, _fill, _direction, acc), do: {:overflow, acc}

  defp bump_with_carry([d | rest], digits, fill, direction, acc) do
    idx = digit_index(digits, d)

    case bump(idx, direction, digits) do
      :wrap ->
        # carry/borrow continues; the current position becomes `fill`
        bump_with_carry(rest, digits, fill, direction, [fill | acc])

      new_d ->
        # digit changed; everything to the left is unchanged.
        new_digs = Enum.reverse(rest, [new_d | acc])
        {:ok, new_digs}
    end
  end

  defp bump(idx, :forward, digits) do
    if idx + 1 == byte_size(digits) do
      :wrap
    else
      String.at(digits, idx + 1)
    end
  end

  defp bump(idx, :backward, digits) do
    if idx == 0 do
      :wrap
    else
      String.at(digits, idx - 1)
    end
  end
end
