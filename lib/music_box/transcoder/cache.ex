defmodule MusicBox.Transcoder.Cache do
  @moduledoc false

  alias MusicBox.Transcoder.{Preset, Result}

  @doc """
  Returns transcoding metadata for a given file/preset.
  """
  @type get_meta_result :: {:ok, Result.t()} | {:error, :not_found}
  @callback get_meta(file_id :: String.t(), preset :: Preset.t()) :: get_meta_result()
  @spec get_meta(file_id :: String.t(), preset :: Preset.t()) :: get_meta_result()
  def get_meta(file_id, preset), do: impl().get_meta(file_id, preset)

  @doc """
  Persists given file/preset to storage in chunks generated by callback.
  """
  @type persist_callback :: (-> Enumerable.t())
  @type persist_result :: :ok | {:error, atom()}
  @callback persist(file_id :: String.t(), preset :: Preset.t(), callback :: persist_callback()) ::
              persist_result()
  @spec persist(file_id :: String.t(), preset :: Preset.t(), callback :: persist_callback()) ::
          persist_result()
  def persist(file_id, preset, callback), do: impl().persist(file_id, preset, callback)

  @doc """
  Returns specific range of bytes from a cached file.
  """
  @callback get_bytes(
              file_id :: String.t(),
              preset :: Preset.t(),
              start_byte :: non_neg_integer(),
              bytes_to_read :: non_neg_integer()
            ) :: iodata()
  @spec get_bytes(
          file_id :: String.t(),
          preset :: Preset.t(),
          start_byte :: non_neg_integer(),
          bytes_to_read :: non_neg_integer()
        ) :: iodata() | nil
  def get_bytes(file_id, preset, start_byte, bytes_to_read),
    do: impl().get_bytes(file_id, preset, start_byte, bytes_to_read)

  defp impl,
    do: Application.get_env(:music_box, MusicBox.Transcoder) |> Keyword.fetch!(:cache_impl)
end
