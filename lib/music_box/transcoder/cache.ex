defmodule MusicBox.Transcoder.Cache do
  @moduledoc false

  alias MusicBox.Transcoder.{Preset, Result}

  @doc """
  Returns transcoding metadata for a given file/preset.
  """
  @type get_meta_result :: {:ok, Result.t()} | {:error, :not_found}
  @callback get_meta(file_id :: String.t(), preset :: Preset.t()) :: get_meta_result()
  @spec get_meta(file_id :: String.t(), preset :: Preset.t()) :: get_meta_result()
  def get_meta(file_id, preset), do: impl().get_meta(file_id, preset)

  @doc """
  Persists given file/preset to storage in chunks generated by callback.
  """
  @type persist_callback :: (-> Enumerable.t())
  @type persist_result :: :ok | {:error, atom()}
  @callback persist(file_id :: String.t(), preset :: Preset.t(), callback :: persist_callback()) ::
              persist_result()
  @spec persist(file_id :: String.t(), preset :: Preset.t(), callback :: persist_callback()) ::
          persist_result()
  def persist(file_id, preset, callback), do: impl().persist(file_id, preset, callback)

  @doc """
  Returns specific range of bytes from a cached file.
  """
  @callback get_bytes(
              file_id :: String.t(),
              preset :: Preset.t(),
              start_byte :: non_neg_integer(),
              bytes_to_read :: non_neg_integer()
            ) :: iodata()
  @spec get_bytes(
          file_id :: String.t(),
          preset :: Preset.t(),
          start_byte :: non_neg_integer(),
          bytes_to_read :: non_neg_integer()
        ) :: iodata() | nil
  def get_bytes(file_id, preset, start_byte, bytes_to_read),
    do: impl().get_bytes(file_id, preset, start_byte, bytes_to_read)

  @typedoc "A cached transcode, the key is the path (or S3 key) of the cached file."
  @type entry :: %{
          key: String.t(),
          file_id: String.t(),
          preset_id: String.t(),
          size: non_neg_integer(),
          completed_at: DateTime.t()
        }

  @doc """
  Lists all cached transcodes, files that are not named like a cached transcode
  are skipped.
  """
  @callback entries() :: [entry()]
  @spec entries() :: [entry()]
  def entries, do: impl().entries()

  @doc """
  Deletes the given cached transcodes.
  """
  @callback delete_entries([entry()]) :: :ok
  @spec delete_entries([entry()]) :: :ok
  def delete_entries(entries), do: impl().delete_entries(entries)

  @doc """
  Parses a cached file name (`{file_id}-{preset_id}.{ext}`) into the file id and
  preset id.
  """
  @spec parse_filename(String.t()) :: {:ok, String.t(), String.t()} | :error
  def parse_filename(filename) do
    case Regex.run(~r/\A([0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12})-(\w+)\.\w+\z/, filename) do
      [_match, file_id, preset_id] -> {:ok, file_id, preset_id}
      nil -> :error
    end
  end

  @doc """
  Deletes the cached file for a given file/preset, if there is one.
  """
  @callback delete(file_id :: String.t(), preset :: Preset.t()) :: :ok | {:error, term()}
  @spec delete(file_id :: String.t(), preset :: Preset.t()) :: :ok | {:error, term()}
  def delete(file_id, preset), do: impl().delete(file_id, preset)

  defp impl,
    do: Application.get_env(:music_box, MusicBox.Transcoder) |> Keyword.fetch!(:cache_impl)
end
