defmodule OnduWeb.Schemas.RecordPlaysRequest do
  @moduledoc false
  alias OnduWeb.Schemas.TrackId
  alias OpenApiSpex.Schema

  require OpenApiSpex

  OpenApiSpex.schema(%{
    title: "RecordPlaysRequest",
    type: :object,
    properties: %{
      plays: %Schema{
        type: :array,
        maxItems: 500,
        items: %Schema{
          type: :object,
          properties: %{
            id: %Schema{
              type: :string,
              format: :uuid,
              description: """
              Generated by the client, should be idempotent so we can ignore
              plays that have already been stored and sent again.
              """
            },
            trackId: TrackId,
            playedAt: %Schema{
              type: :string,
              format: :"date-time",
              description: "When the track started playing."
            }
          },
          required: [:id, :trackId, :playedAt],
          additionalProperties: false
        }
      }
    },
    required: [:plays],
    additionalProperties: false
  })
end

defmodule OnduWeb.Schemas.RecordPlaysResponse do
  @moduledoc false
  alias OpenApiSpex.Schema

  require OpenApiSpex

  OpenApiSpex.schema(%{
    title: "RecordPlaysResponse",
    type: :object,
    properties: %{
      ok: %Schema{type: :boolean, example: true}
    },
    required: [:ok],
    additionalProperties: false
  })
end
